import 'dotenv/config';
import express from 'express';
import mongoose from 'mongoose';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/auth.js';
import enquiryRoutes from './routes/enquiries.js';
import resultRoutes from './routes/results.js';
import paymentRoutes from './routes/payments.js';
import publicRoutes from './routes/public.js';
const app = express();
app.use(helmet());
app.use(cors({ origin: (process.env.CLIENT_URL || 'http://localhost:5173').split(','), credentials: true }));
app.use(express.json({ limit: '20kb' }));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 200, standardHeaders: true, legacyHeaders: false }));
app.get('/api/health', (_req, res) => res.json({ status: 'ok', service: 'Hari College API' }));
app.use('/api/auth', authRoutes);
app.use('/api/enquiries', enquiryRoutes);
app.use('/api/results', resultRoutes);
app.use('/api/payments', paymentRoutes);
app.use('/api', publicRoutes);
app.use((req, res) => res.status(404).json({ message: `Route not found: ${req.method} ${req.path}` }));
app.use((err, _req, res, _next) => { console.error(err); res.status(500).json({ message: 'Server error. Please try again later.' }); });
const port = process.env.PORT || 5000;
try {
  if (!process.env.MONGODB_URI || !process.env.JWT_SECRET) throw new Error('Set MONGODB_URI and JWT_SECRET in .env');
  await mongoose.connect(process.env.MONGODB_URI);
  app.listen(port, () => console.log(`Hari College API running at http://localhost:${port}`));
} catch (error) { console.error('Startup failed:', error.message); process.exit(1); }
